//! Ментальный покер (5.3).
//!
//! Два игрока A и B, три карты: одна A, одна B, одна в прикуп.
//! Открытый параметр — простое p. У каждого игрока секретная пара (c, d),
//! c*d mod (p - 1) = 1, как в шифре Шамира: (R^c)^d mod p = R.
//! Карта — число R = r||код: r — случайное, код — две младшие двоичные цифры.

use crate::math::random_range;

/// Карты с кодами 00, 01, 10
pub const CARDS: [&str; 3] = ["тройка", "семёрка", "туз"];

/// Число карты R = r||код = 4r + код, r — случайное.
/// r >= 1 и R <= p - 2: 0, 1 и p - 1 при возведении в нечётную степень c
/// не меняются, и все бы увидели, какая это карта.
pub fn encode_card(code: u64, p: u64) -> u64 {
    4 * random_range(1, p / 4 - 1) + code
}

/// Карта по числу R — две младшие двоичные цифры
pub fn card(r: u64) -> &'static str {
    CARDS[(r % 4) as usize]
}

/// Случайно перемешивает числа
pub fn shuffle(xs: &mut [u64]) {
    for i in (1..xs.len()).rev() {
        xs.swap(i, random_range(0, i as u64) as usize);
    }
}
