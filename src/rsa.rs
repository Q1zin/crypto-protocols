//! Шифр RSA (2.23).
//!
//! Абонент выбирает простые P и Q. Открытые параметры — N = P*Q и d,
//! секретный — c: c*d mod (P - 1)(Q - 1) = 1.
//! Сообщение m < N для абонента: шаг 1 — e = m^d mod N, шаг 2 — m' = e^c mod N = m.

use crate::math::{inverse, pow_mod};

/// Ключи абонента (N, c): N = P*Q, c = d^(-1) mod (P - 1)(Q - 1).
/// Если d не взаимно просто с (P - 1)(Q - 1), inverse вернёт None — нужно другое d.
pub fn generate_keys(p: u64, q: u64, d: u64) -> Option<(u64, u64)> {
    inverse(d, (p - 1) * (q - 1)).map(|c| (p * q, c))
}

/// Передача сообщения m абоненту с ключами N, d, c. Возвращает (e, m'); должно быть m' = m.
pub fn transmit(m: u64, n: u64, d: u64, c: u64) -> (u64, u64) {
    let e = pow_mod(m, d, n); // шаг 1: отправитель шифрует открытыми N, d
    let m2 = pow_mod(e, c, n); // шаг 2: получатель расшифровывает секретным c
    (e, m2)
}
